export function getTeamLogo(teamNameOrShort) {
  if (!teamNameOrShort) return null;
  const t = String(teamNameOrShort).toLowerCase().trim();

  // IPL Teams
  if (t === 'csk' || t.includes('chennai')) return TEAM_LOGOS.CSK;
  if (t === 'mi' || t === 'mumbai' || t.includes('mumbai')) return TEAM_LOGOS.MI;
  if (t === 'rcb' || t.includes('bengaluru') || t.includes('bangalore')) return TEAM_LOGOS.RCB;
  if (t === 'kkr' || t.includes('kolkata')) return TEAM_LOGOS.KKR;
  if (t === 'srh' || t.includes('hyderabad')) return TEAM_LOGOS.SRH;
  if (t === 'rr' || t.includes('rajasthan')) return TEAM_LOGOS.RR;
  if (t === 'gt' || t.includes('gujarat')) return TEAM_LOGOS.GT;
  if (t === 'lsg' || t.includes('lucknow')) return TEAM_LOGOS.LSG;
  if (t === 'dc' || t.includes('delhi')) return TEAM_LOGOS.DC;
  if (t === 'pbks' || t.includes('punjab')) return TEAM_LOGOS.PBKS;

  // Historical IPL Teams
  if (t === 'kxip' || t.includes('kings xi')) return TEAM_LOGOS.KXIP;
  if (t === 'dd' || t.includes('daredevils')) return TEAM_LOGOS.DD;
  if (t === 'dcg' || t === 'dch' || t.includes('deccan')) return TEAM_LOGOS.DCG;
  if (t === 'gl' || t.includes('gujarat lions')) return TEAM_LOGOS.GL;
  if (t === 'rps' || t.includes('rising pune')) return TEAM_LOGOS.RPS;
  if (t === 'pwi' || t.includes('pune warriors')) return TEAM_LOGOS.PWI;
  if (t === 'ktk' || t.includes('kochi')) return TEAM_LOGOS.KTK;

  // SA20 Teams
  if (t === 'jsk' || t.includes('joburg')) return TEAM_LOGOS.JSK;
  if (t === 'mict' || t.includes('cape town')) return TEAM_LOGOS.MICT;
  if (t === 'pr' || t.includes('paarl')) return TEAM_LOGOS.PR;
  if (t === 'dsg' || t.includes('durban')) return TEAM_LOGOS.DSG;
  if (t === 'sec' || t.includes('eastern cape')) return TEAM_LOGOS.SEC;
  if (t === 'pc' || t.includes('pretoria')) return TEAM_LOGOS.PC;

  // MLC Teams
  if (t === 'tsk' || t.includes('texas')) return TEAM_LOGOS.TSK;
  if (t === 'miny' || t.includes('new york')) return TEAM_LOGOS.MINY;
  if (t === 'seo' || t.includes('seattle')) return TEAM_LOGOS.SEO;
  if (t === 'lakr' || t.includes('los angeles')) return TEAM_LOGOS.LAKR;
  if (t === 'waf' || t.includes('washington')) return TEAM_LOGOS.WAF;
  if (t === 'sfu' || t.includes('san francisco')) return TEAM_LOGOS.SFU;

  return null;
}
